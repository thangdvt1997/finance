import { chromium } from "playwright";
const BASE = process.env.BASE || "http://127.0.0.1:8581/c/";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 414, height: 896 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror", e.message));
page.on("console", (m) => { if (m.type() === "error" && !m.text().includes("WebSocket")) console.log("console", m.text().slice(0, 150)); });
await page.goto(`${BASE}?mock=1&mockprefs=off`);
await page.evaluate(() => { localStorage.clear(); localStorage.setItem("tc-prefs", JSON.stringify({ lang: "en", onboarded: true })); });
await page.reload(); await page.waitForSelector("form");
await page.fill('input[autocomplete="username"]', "12345678"); await page.fill('input[autocomplete="current-password"]', "demo-cong-1");
await page.click('button[type="submit"]'); await page.waitForSelector("main#main-content");
await page.waitForTimeout(2500);
const dump = async (l) => console.log(l, await page.evaluate(() => { const m = JSON.parse(localStorage.getItem("tc-mock-prefs") || "null"); const p = JSON.parse(localStorage.getItem("tc-prefs") || "{}"); return JSON.stringify({ srv: m && { rev: m.rev, theme: m.data.theme, density: m.data.density, lang: m.data.lang }, local: { theme: p.theme, density: p.density }, sess: sessionStorage.getItem("tc-mock-prefs-mode"), st: [...document.querySelectorAll('[role=status]')].map((e) => e.textContent.slice(0, 60)) }); }));
await dump("baseline");
await page.goto(`${BASE}?mock=1&mockprefs=409#/ho-so`); await page.waitForTimeout(2000);
await dump("after goto409");
console.log(await page.evaluate(() => [...document.querySelectorAll("button[aria-pressed]")].map((e) => e.textContent).join(",")));
await page.click('button[aria-pressed]:has-text("Dark")'); await page.waitForTimeout(4500);
await dump("after dark");
await page.goto(`${BASE}?mock=1&mockprefs=404#/ho-so`); await page.waitForTimeout(2500);
await dump("after 404");
await b.close();
